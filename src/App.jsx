  function handleSaveNote(note, deleteId) {
    let notes = [...(data.notes || [])];
    if (deleteId) {
      notes = notes.filter(n => n.id !== deleteId);
    } else if (note) {
      notes = [...notes, note];
    }
    commit({ ...data, notes });
  }

